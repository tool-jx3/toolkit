export interface LunarFestivals {
  /** 正月初一（春節第一天） */
  newYear: string;
  /** 五月初五（端午節） */
  dragonBoat: string;
  /** 八月十五（中秋節） */
  midAutumn: string;
  /** 清明（民族掃墓節／清明節） */
  qingming: string;
}

const iso = (year: number, mmdd: string) => `${year}-${mmdd.slice(0, 2)}-${mmdd.slice(2, 4)}`;

/** 這一年的農曆節日與清明；表外的年份 null */
export function lunarFestivals(year: number): LunarFestivals | null {
  if (!Number.isInteger(year) || year < LUNAR_FIRST_YEAR || year > LUNAR_LAST_YEAR) return null;
  const [ny, db, ma, qm] = TABLE[year - LUNAR_FIRST_YEAR].split(' ');
  return {
    newYear: iso(year, ny),
    dragonBoat: iso(year, db),
    midAutumn: iso(year, ma),
    qingming: iso(year, `040${qm}`),
  };
}
