const CAT_ORDER = ['floor', 'wall', 'prop', 'character', 'item'];

function tinyDefs(): TileDef[] {
  const list = TINY_INFO.map(([name, cat], i) => ({
    id: `kt:${i}`,
    name,
    src: TINY_SRC,
    rect: [(i % 12) * 17, Math.floor(i / 12) * 17, 16, 16] as const,
    pixel: true,
    cat,
    set: TINY_SET,
  }));
  /* 調色盤上依分類排（同分類照圖上的順序） */
  return list
    .map((d, i) => ({ d, i }))
    .sort((a, b) => CAT_ORDER.indexOf(a.d.cat) - CAT_ORDER.indexOf(b.d.cat) || a.i - b.i)
    .map((x) => x.d);
}

export const SCRIBBLE_TILES: readonly TileDef[] = scribbleDefs();
export const TINY_TILES: readonly TileDef[] = tinyDefs();
