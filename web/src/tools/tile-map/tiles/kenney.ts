/** 調色盤上的順序：上面的資訊表依分類排好的順序；同一個東西「附地板」的版本緊接在後 */
function scribbleDefs(): TileDef[] {
  const out: TileDef[] = [];
  for (const [base, [name, cat]] of Object.entries(SCRIBBLE_INFO)) {
    for (const file of [base, `floor_${base}`]) {
      const i = (SCRIBBLE_FILES as readonly string[]).indexOf(file);
      if (i < 0) continue;
      out.push({
        id: `ks:${file}`,
        name: file === base ? name : `${name}（附地板）`,
        src: SCRIBBLE_SRC,
        rect: [(i % 12) * 64, Math.floor(i / 12) * 64, 64, 64],
        pixel: false,
        cat,
        set: SCRIBBLE_SET,
      });
    }
  }
  return out;
}

