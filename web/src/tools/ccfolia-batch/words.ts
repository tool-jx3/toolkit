/** 比對用的寫法：NFKC（全形英數、全形括號 → 半形）、小寫、去掉所有空白 */
export function wordKey(s: unknown): string {
  return String(s ?? '')
    .normalize('NFKC')
    .toLowerCase()
    .replace(/\s+/g, '');
}

