type Ids = readonly string[];

const core = (
  id: string,
  tone: string,
  title: string,
  text: string,
  climaxes: Ids,
  missions: Ids,
  truths: Ids,
  endings: Ids,
): Card =>
  card('core', id, title, text, CORE_QUESTION, climaxes, {
    tones: [tone],
    missions,
    truths: truths.map((t) => `truth.${t}`),
    endings: endings.map((e) => `ending.${e}`),
  });

