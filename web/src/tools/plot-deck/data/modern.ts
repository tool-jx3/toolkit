type Ids = readonly string[];

/** 餘韻：一種氣氛、三個高潮的例子、合的題材、真相與結局 */
const core = (
  id: string,
  tone: string,
  title: string,
  text: string,
  climaxes: Ids,
  missions: Ids,
  truths: Ids,
  endings: Ids,
): Card =>
  card('core', id, title, text, CORE_QUESTION, climaxes, {
    tones: [tone],
    missions,
    truths: truths.map((t) => `truth.${t}`),
    endings: endings.map((e) => `ending.${e}`),
  });

/** 焦點：一種氣氛 */
const mood = (
  id: string,
  tone: string,
  title: string,
  text: string,
  question: string,
  answers: Ids,
  missions: Ids,
): Card => card('tone', id, title, text, question, answers, { tones: [tone], missions });

